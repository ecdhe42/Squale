CHECK_KEYBOARD
    LDA $F046
    CMPA #$FF
    LBEQ MAIN_LOOP
    LDY PLAYER_POS

    CMPA #$FE
    LBEQ KEYBOARD_UP
    CMPA #$7F
    LBEQ KEYBOARD_DOWN
    CMPA #$DF
    LBEQ KEYBOARD_LEFT
    CMPA #$BF
    LBEQ KEYBOARD_RIGHT
    JMP MAIN_LOOP

****************************
* END OF MAIN LOOP
****************************

KEYBOARD_RIGHT
    CMPY #45
    BEQ RIGHT_RESET
    LDA #6
    STA LINE_COLOR,Y
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    LDA #1
    STA LINE_COLOR+4,Y
    STA LINE_COLOR+5,Y
    CMPY #42
    BEQ KEYBOARD_RIGHT_DRAW_FIRST_VECTOR
    STA LINE_COLOR+6,Y
    BRA MOVE_PLAYER_RIGHT
KEYBOARD_RIGHT_DRAW_FIRST_VECTOR
    STA LINE_COLOR-42,Y
MOVE_PLAYER_RIGHT
    LEAY 3,Y
    STY PLAYER_POS
    JMP MAIN_LOOP
RIGHT_RESET
    LDA #6
    STA LINE_COLOR,Y
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    LDY #0
    STY PLAYER_POS
    LDA #1
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    STA LINE_COLOR+3,Y
    JMP MAIN_LOOP

KEYBOARD_LEFT
    CMPY #0
    BEQ LEFT_RESET
    LDA #6
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    CMPY #45
    BEQ KEYBOARD_LEFT_ERASE_FIRST_VECTOR
    STA LINE_COLOR+3,Y
    BRA MOVE_PLAYER_LEFT
KEYBOARD_LEFT_ERASE_FIRST_VECTOR
    STA LINE_COLOR
MOVE_PLAYER_LEFT
    LDA #1
    STA LINE_COLOR-1,Y
    STA LINE_COLOR-2,Y
    STA LINE_COLOR-3,Y
    LEAY -3,Y
    STY PLAYER_POS
    JMP MAIN_LOOP
LEFT_RESET
    LDA #6
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    STA LINE_COLOR+3,Y
    LDY #45
    STY PLAYER_POS
    LDA #1
    STA LINE_COLOR,Y
    STA LINE_COLOR+1,Y
    STA LINE_COLOR+2,Y
    JMP MAIN_LOOP

KEYBOARD_UP
    JMP MAIN_LOOP
KEYBOARD_DOWN
    JMP MAIN_LOOP

END_PRG
    BRA END_PRG

