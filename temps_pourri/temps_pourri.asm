GPU_CMD     EQU $F000
GPU_DX      EQU $F005
GPU_DY      EQU $F007
GPU_X_MSB   EQU $F008
GPU_X_LSB   EQU $F009
GPU_Y_MSB   EQU $F00A
GPU_Y_LSB   EQU $F00B
GPU_COLOR   EQU $F010

MAZE_NB_LINES   EQU 48
PLAYER_POS  EQU $5800
ENEMY_POS   EQU $5802
MISSILE_POS1   EQU $5804
MISSILE_POS2   EQU $5806
MISSILE_POS3   EQU $5808
MISSILE_POS4   EQU $580A
MISSILE_POS5   EQU $580C

    ORG $0000
    SETDP $F0

    LDA #$F0
    EXG A,DP

WAIT_VIDEO_CHIP
    LDA GPU_CMD
    ANDA #4
    BEQ WAIT_VIDEO_CHIP

    CLR GPU_COLOR

WAIT_VIDEO_CHIP2
    LDA GPU_CMD
    ANDA #4
    BEQ WAIT_VIDEO_CHIP2

****************************
* INIT
****************************
    LDY #0
    STY PLAYER_POS
*    LDY #MAZE_NB_LINES
    STY ENEMY_POS
    LDY #50
    STY MISSILE_POS1
    LDY #160
    STY MISSILE_POS2
    LDY #300
    STY MISSILE_POS3
    LDY #490
    STY MISSILE_POS4
    LDY #710
    STY MISSILE_POS5

****************************
* MAIN LOOP
****************************
MAIN_LOOP
    JSR VBLANK
    JSR CLEAR_SCREEN

    LDX #MAZE_NB_LINES
LINE_LOOP
    LEAX -1,X
    JSR DRAW_LINE
    CMPX #0
    BNE LINE_LOOP
****************** DRAW ENEMY
    LDY ENEMY_POS           * Draw enemy
    JSR DRAW_ENEMY_LINE
    LEAY 1,Y
    JSR DRAW_ENEMY_LINE
    CMPY #1599                * If enemy ptr is 73
    BEQ RESET_ENEMY
    LEAY 1,Y
    STY ENEMY_POS
    BRA DRAW_MISSILE
RESET_ENEMY
    LDY #0
    STY ENEMY_POS

DRAW_MISSILE
****************** DRAW MISSILE
    LDY MISSILE_POS1           * Draw enemy
    JSR DRAW_MISSILE_LINE
    LEAY 1,Y
    JSR DRAW_MISSILE_LINE
    CMPY #1599                * If enemy ptr is 73
    BEQ RESET_MISSILE1
    LEAY 1,Y
    STY MISSILE_POS1
    BRA DRAW_MISSILE2
RESET_MISSILE1
    LDY #0
    STY MISSILE_POS1

DRAW_MISSILE2
    LDY MISSILE_POS2           * Draw enemy
    JSR DRAW_MISSILE_LINE
    LEAY 1,Y
    JSR DRAW_MISSILE_LINE
    CMPY #1599                * If enemy ptr is 73
